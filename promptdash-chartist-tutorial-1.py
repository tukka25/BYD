from unsloth import FastLanguageModel
import torch

max_seq_length = 4096

model, tokenizer = FastLanguageModel.from_pretrained(
    "unsloth/Qwen3-4B-Instruct-2507-bnb-4bit",
    load_in_4bit = True, # Use 4bit to reduce memory use. False for 16bit LoRA.
    dtype = None,
    use_gradient_checkpointing = "unsloth", # True or "unsloth" for long context
)

from datasets import load_dataset

dataset = load_dataset(
    "json",
    data_files="plotly_qwen_train.jsonl",
    split="train"
)

from unsloth.chat_templates import get_chat_template


tokenizer = get_chat_template(
    tokenizer,
    chat_template = "qwen-3", # change this to the right chat_template name based on model
    )

def formatting_prompts_func(examples):
   convos = examples["messages"]  # the data is inside conversations key
   texts = [tokenizer.apply_chat_template(convo,
             tokenize = False,
             add_generation_prompt = False)
             for convo in convos]
   return { "text" : texts, }

# Apply the formatting function to the dataset using the map method
dataset = dataset.map(formatting_prompts_func, batched = True,)

# lastly, check the transformed dataset
dataset['text'][0]

model = FastLanguageModel.get_peft_model(
                model,
                r=16,
                target_modules=[
                                "q_proj",
                                "k_proj",
                                "v_proj",
                                "o_proj",
                                "gate_proj",
                                "up_proj",
                                "down_proj",
                ],
                lora_alpha=32,
                lora_dropout=0,
                bias="none",
                use_gradient_checkpointing="unsloth",
                random_state=42,
                use_rslora=False,
                loftq_config=None,
)

from trl import SFTTrainer
from transformers import TrainingArguments

# Training arguments optimized for Unsloth
trainer = SFTTrainer(
    model=model,
    tokenizer=tokenizer,
    train_dataset=dataset,
    dataset_text_field="text",
    max_seq_length=max_seq_length,
    dataset_num_proc=2,
    args=TrainingArguments(
        per_device_train_batch_size=2,
        gradient_accumulation_steps=4,  # Effective batch size = 8
        warmup_steps=10,
        num_train_epochs=3,
        learning_rate=2e-4,
        fp16=not torch.cuda.is_bf16_supported(),
        bf16=torch.cuda.is_bf16_supported(),
        logging_steps=25,
        optim="adamw_8bit",
        weight_decay=0.01,
        lr_scheduler_type="linear",
        seed=42,    # for reproducible results hopefully!
        output_dir="outputs",
        save_strategy="epoch",
        save_total_limit=2,
        dataloader_pin_memory=False,
        report_to="none", # Disable Weights & Biases logging
    ),
)

trainer_Stats = trainer.train()  # train it

# lets see our inside first
FastLanguageModel.for_inference(model)

def chat_with_model(query:str):

    # Test prompt -> It exactly matches the format that tokenizer.apply_chat_template is configured to understand.
    messages = [
        {"role": "user",
         "content": query},
    ]

    inputs = tokenizer.apply_chat_template(
        messages,
        tokenize=True,
        add_generation_prompt=True,
        return_tensors="pt",
    ).to("cuda")

    # Generate response
    outputs = model.generate(
        input_ids=inputs,
        max_new_tokens=1024,
        use_cache=False, # Changed to False to prevent the RuntimeError
        temperature=0.1,
        do_sample=True,
        top_p=0.9,
        eos_token_id=tokenizer.eos_token_id,
    )

    # Decode and print
    response = tokenizer.decode(outputs[0], skip_special_tokens=False)
    return response

print(chat_with_model("Can you create a volcano plot chart using Plotly Python? Focus on: Point Sizes And Line Widths. Details: Detailed examples of Volcano Plot including changing color, size, log axes, and more in Python.. Return only Python code"))